// 0.2.1 B6: XML comments and CDATA in styles.xml and in the worksheet head no longer make a workbook read-only.
// The patcher masks them (offsets stay the same), keeps them byte for byte, and never finds a fake tag inside one.
// A comment or CDATA section that is not closed (or "--" inside a comment) stays blocked.
const { test } = require('node:test');
const assert = require('node:assert/strict');
const JSZip = require('jszip');

const S = require('../.out/sheet.js');

const NS = 'http://schemas.openxmlformats.org/spreadsheetml/2006/main';
const NS_R = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships';
const REL = NS_R;
const CT = 'application/vnd.openxmlformats-officedocument.spreadsheetml';
const DECL = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n';

const STYLES = (extra = {}) =>
  `${DECL}${extra.beforeRoot ?? ''}<styleSheet xmlns="${NS}">${extra.top ?? ''}` +
  '<numFmts count="1"><numFmt numFmtId="164" formatCode="0.000"/></numFmts>' +
  `<fonts count="1">${extra.inFonts ?? ''}<font><sz val="11"/><name val="Calibri"/></font></fonts>` +
  '<fills count="2"><fill><patternFill patternType="none"/></fill><fill><patternFill patternType="gray125"/></fill></fills>' +
  '<borders count="1"><border><left/><right/><top/><bottom/><diagonal/></border></borders>' +
  '<cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs>' +
  `${extra.beforeXfs ?? ''}<cellXfs count="2"><xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0"/>${extra.inXfs ?? ''}` +
  '<xf numFmtId="164" fontId="0" fillId="0" borderId="0" xfId="0" applyNumberFormat="1"/></cellXfs>' +
  '<cellStyles count="1"><cellStyle name="Normal" xfId="0" builtinId="0"/></cellStyles></styleSheet>';

const sheet = (head, rows = '<row r="1"><c r="A1"><v>1</v></c><c r="B1"><v>2</v></c></row>') =>
  `${DECL}<worksheet xmlns="${NS}" xmlns:r="${NS_R}">${head}<sheetData>${rows}</sheetData></worksheet>`;

async function makeXlsx(sheetXml, stylesXml) {
  const zip = new JSZip();
  zip.file('xl/worksheets/sheet1.xml', sheetXml);
  zip.file('xl/styles.xml', stylesXml);
  zip.file('xl/sharedStrings.xml', `${DECL}<sst xmlns="${NS}" count="1" uniqueCount="1"><si><t>zero</t></si></sst>`);
  zip.file('xl/workbook.xml', `${DECL}<workbook xmlns="${NS}" xmlns:r="${NS_R}"><sheets><sheet name="S1" sheetId="1" r:id="rId1"/></sheets><calcPr calcId="191029"/></workbook>`);
  zip.file('xl/_rels/workbook.xml.rels', `${DECL}<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">` +
    `<Relationship Id="rId1" Type="${REL}/worksheet" Target="worksheets/sheet1.xml"/>` +
    `<Relationship Id="rIdS" Type="${REL}/styles" Target="styles.xml"/>` +
    `<Relationship Id="rIdT" Type="${REL}/sharedStrings" Target="sharedStrings.xml"/></Relationships>`);
  zip.file('_rels/.rels', `${DECL}<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="${REL}/officeDocument" Target="xl/workbook.xml"/></Relationships>`);
  zip.file('[Content_Types].xml', `${DECL}<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">` +
    '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/>' +
    `<Override PartName="/xl/workbook.xml" ContentType="${CT}.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="${CT}.worksheet+xml"/>` +
    `<Override PartName="/xl/styles.xml" ContentType="${CT}.styles+xml"/><Override PartName="/xl/sharedStrings.xml" ContentType="${CT}.sharedStrings+xml"/></Types>`);
  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}

const partText = async (bytes, name) => (await JSZip.loadAsync(bytes)).file(name).async('string');
const cells = (list) => [{ kind: 'cells', sheet: 1, cells: list }];
const num = (v) => ({ t: 'n', v });

const FAKE_XFS = '<!-- <cellXfs count="1"><xf/></cellXfs> -->';
const FAKE_SD = '<!-- <sheetData><row r="1"><c r="A1"><v>1</v></c></row></sheetData> -->';

test('B6: comments and CDATA in styles.xml are patchable, and a derived style keeps every comment byte for byte', async () => {
  const styles = STYLES({
    beforeRoot: '<!-- generated by a tool -->\n',
    top: '<![CDATA[ <fonts count="9"> ]]>',
    inFonts: '<!-- <font><b/></font> -->',
    beforeXfs: FAKE_XFS,
    inXfs: '<!-- <xf numFmtId="9"/> -->',
  });
  const base = await makeXlsx(sheet('<!-- head note -->'), styles);
  assert.deepEqual(await S.checkPatchable(base), { ok: true });
  const ops = cells([[0, 0, { value: num(5), style: [{ bold: true }] }]]);
  const { bytes } = await S.buildXlsx(base, ops);
  await S.verifyXlsx(base, bytes, ops, [{ sheet: 1, r: 0, c: 0, value: num(5), styleIndex: 2 }]);
  const after = await partText(bytes, 'xl/styles.xml');
  // The real sections are patched, the commented fakes are untouched.
  assert.match(after, /<fonts count="2">/);
  assert.match(after, /<cellXfs count="3">/);
  assert.ok(after.includes(FAKE_XFS) && after.includes('<!-- generated by a tool -->') && after.includes('<![CDATA[ <fonts count="9"> ]]>'));
  assert.ok(after.includes('<!-- <font><b/></font> -->') && after.includes('<!-- <xf numFmtId="9"/> -->'));
  const sheetAfter = await partText(bytes, 'xl/worksheets/sheet1.xml');
  assert.ok(sheetAfter.includes('<!-- head note -->'));
  assert.match(sheetAfter, /<c r="A1" s="2"><v>5<\/v><\/c>/);
});

test('B6: a new custom number format is added when styles.xml has comments (numFmts inserted after the real root tag)', async () => {
  const noFmts = STYLES({ beforeRoot: '<!-- <styleSheet> -->' }).replace(/<numFmts[\s\S]*?<\/numFmts>/, '');
  const base = await makeXlsx(sheet(''), noFmts);
  const ops = cells([[0, 0, { value: num(5), style: [{ numFmt: '0.0000' }] }]]);
  const { bytes } = await S.buildXlsx(base, ops);
  const after = await partText(bytes, 'xl/styles.xml');
  assert.match(after, /<styleSheet [^>]*><numFmts count="1"><numFmt numFmtId="165" formatCode="0.0000"\/><\/numFmts>/);
  assert.ok(after.includes('<!-- <styleSheet> -->'));
});

test('B6: a comment or CDATA section in the worksheet head is patchable (also one that holds a fake <sheetData> or <dimension>)', async () => {
  const head = `<!-- <dimension ref="A1:A1"/> -->${FAKE_SD}<dimension ref="A1:B1"/><![CDATA[ <sheetData> ]]><cols><col min="1" max="1" width="9"/></cols>`;
  const base = await makeXlsx(sheet(head), STYLES());
  assert.deepEqual(await S.checkPatchable(base), { ok: true });
  const ops = cells([[0, 0, { value: num(7) }], [0, 5, { value: num(8) }]]);
  const { bytes } = await S.buildXlsx(base, ops);
  await S.verifyXlsx(base, bytes, ops, [{ sheet: 1, r: 0, c: 0, value: num(7), styleIndex: 0 }]);
  const after = await partText(bytes, 'xl/worksheets/sheet1.xml');
  assert.ok(after.startsWith(`${DECL}<worksheet xmlns="${NS}" xmlns:r="${NS_R}">${head.replace('A1:B1', 'A1:F1')}<sheetData>`));
  assert.match(after, /<c r="A1"><v>7<\/v><\/c><c r="B1"><v>2<\/v><\/c><c r="F1"><v>8<\/v><\/c>/);
});

test('B6: a comment that is not closed, or has "--" inside, still makes the workbook read-only (fail closed)', async () => {
  const ok = sheet('');
  for (const styles of [STYLES({ top: '<!-- never closed' }), STYLES({ top: '<![CDATA[ never closed' }), STYLES({ top: '<!-- a -- b -->' })]) {
    const bad = await S.checkPatchable(await makeXlsx(ok, styles));
    assert.equal(bad.ok, false);
    assert.match(bad.reason, /comment/);
  }
  for (const head of ['<!-- never closed <dimension ref="A1"/>', '<!-- a -- b -->']) {
    const bad = await S.checkPatchable(await makeXlsx(sheet(head), STYLES()));
    assert.equal(bad.ok, false);
  }
});

test('B6: a comment inside a row stays blocked', async () => {
  const inRow = await S.checkPatchable(await makeXlsx(sheet('', '<row r="1"><!-- <c r="B1"/> --><c r="A1"><v>1</v></c></row>'), STYLES()));
  assert.equal(inRow.ok, false);
  assert.match(inRow.reason, /comment or CDATA/);
});

test('B6 r1: a comment or CDATA inside a style item (font, xf, border) is refused up front, not at save time', async () => {
  const inItem = [
    STYLES().replace('<font><sz val="11"/>', '<font><!-- c --><sz val="11"/>'),
    STYLES().replace('<border><left/>', '<border><![CDATA[x]]><left/>'),
    STYLES().replace('<xf numFmtId="164" fontId="0"', '<xf numFmtId="164" fontId="0"><!-- c --></xf><xf fontId="0"'),
  ];
  for (const styles of inItem) {
    const r = await S.checkPatchable(await makeXlsx(sheet(''), styles));
    assert.equal(r.ok, false, 'refused before any edit is accepted');
    assert.match(r.reason, /comment or CDATA/);
  }
  // between items stays fine
  assert.deepEqual(await S.checkPatchable(await makeXlsx(sheet(''), STYLES({ inFonts: '<!-- x -->', inXfs: '<!-- y -->' }))), { ok: true });
});
